        internal void MoveBy(double moveBy)
        {
            double time = 0;
            if (MediaPlayer != null)
            {
                if (MediaPlayer.IsPlaying)
                {
                    time = MediaPlayer.Length * MediaPlayer.Position;
                }
                else if (!MediaPlayer.IsPlaying && paused)
                {
                    time = MediaPlayer.Length * MediaPlayer.Position;
                }

                time += moveBy * 1000;

                if (time > MediaPlayer.Length) time = MediaPlayer.Length - 5000;

                MediaPlayer.SeekTo(TimeSpan.FromMilliseconds(time));

                //MainWindowViewModel? vm = GetMainWindowViewModel();
                SetPercent();

                Console.Out.WriteLine("Percent=" + Percent);
            }
        }


                    // if last character of path = . or .. it is a parent folder;

                    string dir = System.IO.Path.GetDirectoryName(Path);
                    int len = dir.Length;
                    string pathFolder = Path.Substring(len + 1);
                    if (pathFolder == "." || pathFolder == "..")
                    {
                        // new folder add name to folder
                        Path = pathFolder + Name;
                        if (Directory.Exists(Path))
                        {
                        }
                        else
                        {
                            Directory.CreateDirectory(Path);
                        }
                        this.ImageItems.Clear();
                        this.ImageItems.ReloadImageItems(value);
                    }
                    else
                    {
                        // changing the name
                        string newPath = dir + @"\" + name;
                        if (!Directory.Exists(newPath) && Directory.Exists(Path))
                        {
                            // we can move
                            if (Path.ToLower() != newPath.ToLower())
                                Directory.Move(Path, newPath);
                            else Directory.CreateDirectory(Path);
                            this.ImageItems.Clear();
                            this.ImageItems.ReloadImageItems(value);
                        }

                        if (path != newPath)
                        {
                            Path = newPath;
                            Save();
                        }
                    }
                }
            }

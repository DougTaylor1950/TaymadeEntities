        public static string Heading1ID(string chapId)
        {
            //construct the string id
            string stringId = string.Empty;
            if (int.TryParse(chapId, out int sectNum))
            {
                stringId = Heading1ID(sectNum);
            }
            return stringId;
        }

        public static string Heading1ID(int chapNum)
        {
            string stringId = "heading1_";
            return stringId += chapNum.ToString("00");
        }

        public static string Heading2ID(string chapId, string head2Num)
        {
            //construct the string id
            string stringId = "heading2_";
            if (int.TryParse(chapId, out int sectNum))
            {
                stringId += sectNum.ToString("00");

                // add in section 2 pos 
                if (int.TryParse(head2Num, out int head2NumInt))
                {
                    stringId += "_" + head2NumInt.ToString("00");
                }
            }
            return stringId;
        }

        public static string SectionID(int sectNum)

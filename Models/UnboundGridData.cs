    /// <summary>
    /// Defines the <see cref="UnboundGridDataCollection" />.
    /// </summary>
    public class UnboundGridDataCollection : List<UnboundGridData>
    {
        #region Fields

        /// <summary>
        /// Defines the creationCol.
        /// </summary>
        private int creationCol = 3;

        /// <summary>
        /// Defines the fileLengthCol.
        /// </summary>
        private int fileLengthCol = 2;

        /// <summary>
        /// Defines the fileNameCol.
        /// </summary>
        private int fileNameCol = 1;

        /// <summary>
        /// Defines the folderDirection.
        /// </summary>
        private int folderDirection = 0;

        #endregion

        #region Constructors

        /// <summary>
        /// Initializes a new instance of the <see cref="UnboundGridDataCollection"/> class.
        /// </summary>
        public UnboundGridDataCollection()
        {
            List<UnboundGridData> unbounds = DataController.SandboxEntities.UnboundGridData.ToList();

            foreach (var item in unbounds)
            {
                Add(item);
            }
        }

        /// <summary>
        /// Initializes a new instance of the <see cref="UnboundGridDataCollection"/> class.
        /// </summary>
        /// <param name="list">The list<see cref="List{UnboundGridData}"/>.</param>
        public UnboundGridDataCollection(List<UnboundGridData> list)
        {
            foreach (var item in list)
            {
                Add(item);
            }
        }

        public UnboundGridDataCollection(IEnumerable<UnboundGridData> collection) : base(collection)
        {
        }

        #endregion

        #region Methods

        /// <summary>
        /// The SortByColumn.
        /// </summary>
        /// <param name="column">The column<see cref="int"/>.</param>
        /// <param name="direction">The direction<see cref="ListSortDirection"/>.</param>
        public void SortByColumn(int column, ListSortDirection direction)
        {
            if (column == folderDirection)
            {
                if (direction == ListSortDirection.Ascending)
                    Sort((x, y) => x.Folder.CompareTo(y.Folder));
                if (direction == ListSortDirection.Descending)
                    Sort((x, y) => y.Folder.CompareTo(x.Folder));
            }
            else if (column == fileNameCol)
            {
                if (direction == ListSortDirection.Ascending)
                    Sort((x, y) => x.FileName!.CompareTo(y.FileName));
                if (direction == ListSortDirection.Descending)
                    Sort((x, y) => y.FileName!.CompareTo(x.FileName));
            }
            else if (column == fileLengthCol)
            {
                if (direction == ListSortDirection.Ascending)
                    Sort((x, y) => x.FileLength.Value.CompareTo(y.FileLength.Value));
                if (direction == ListSortDirection.Descending)
                    Sort((x, y) => y.FileLength.Value.CompareTo(x.FileLength.Value));
            }
            else if (column == creationCol)
            {
                if (direction == ListSortDirection.Ascending)
                    Sort((x, y) => x.CreationTime.CompareTo(y.CreationTime));
                if (direction == ListSortDirection.Descending)
                    Sort((x, y) => y.CreationTime.CompareTo(x.CreationTime));
            }
        }

        /// <summary>
        /// The SortByColumn.
        /// </summary>
        /// <param name="column">The column<see cref="string"/>.</param>
        /// <param name="direction">The direction<see cref="int"/>.</param>
        public void SortByColumn(string column, int direction)
        {
            int SortColumn = 0;
            if (column == "File Length") SortColumn = 2;
            else if (column == "Name") SortColumn = 1;

            else if (column == "Creation Time") SortColumn = 3;

            ListSortDirection sortDirection = ListSortDirection.Ascending;
            if (direction < 1) sortDirection = ListSortDirection.Descending;

            SortByColumn(SortColumn, sortDirection);
        }

        #endregion
    }

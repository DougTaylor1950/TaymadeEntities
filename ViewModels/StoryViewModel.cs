        public string ReadDataFromTxtFileWithUTF8Encoding(string txtFilePath)
        {
            string fileContent = string.Empty;
            if (File.Exists(txtFilePath))
            {
                using var reader = new StreamReader(File.OpenRead(txtFilePath), Encoding.UTF8);
                while (!reader.EndOfStream)
                {
                    var line = reader.ReadToEnd();
                    if (!String.IsNullOrEmpty(line))
                    {
                        fileContent += line;
                    }
                }
            }

            return fileContent;
        }

        /// <summary>
        /// Reformats the document converting into paragraphs and removing unwanted characters.
        /// </summary>
        /// <param name="newStoryPath">The new story path.</param>
        /// <autogeneratedoc />
        private void ReformatDocument(string newStoryPath)
        {
            // read entire text file into a string variable
            string text = FileSupport.ReadDataFromTxtFileFindEncoding(newStoryPath);
            // string text = ReadDataFromTxtFileWithUTF8Encoding(newStoryPath);
            // replace all instances of \r\n with \n    
            text = text.Replace("\r\n", "\n");
            // replace all instances of \r with \n
            text = text.Replace("\r", "\n");
            // replace all instances of \n + whitespace with \n\n
            text = text.Replace("\n ", "\n\n");
            //replace all instances of space + \n with \n
            text = text.Replace(" \n", "\n");
            // replace all instances of \n + \n with '~'
            text = text.Replace("\n\n", "~");
            // replace all instances of \n with ' '
            text = text.Replace("\n", " ");
            // replace all instances of '~' with '\n'
            text = text.Replace("~", "\n");

            // replace all "..." with ellipsis
            text = text.Replace("...", "…");
            // replace all instances of regullar expression  [A-z],[A-z] with [A-z], [A-z]
            text = System.Text.RegularExpressions.Regex.Replace(text, @"([A-Za-z]),([A-Za-z])", "$1, $2");

            // replace all form feeds ^L with text "<BREAK>"
            text = text.Replace("\f", "<BREAK>");

            // replace all characters = decimal value 65533 with a single quote
            text = text.Replace("\uFFFD", "'");

            // write the text back to the file
            File.WriteAllText(newStoryPath, text);

            // go through all text looking for double quote, if preceding character is a number replace with a closing quote,
            // if not if starting quote replace with opening quote else a closing quote
            bool openingQuote = true;
            bool openingSingleQuote = true;

            // loop through each character in the text
            for (int i = 0; i < text.Length; i++)
            {
                if (text[i] == '"')
                {
                    // check preceding character is a number
                    if (i > 0 && char.IsDigit(text[i - 1]))
                    {
                        // replace with closing quote
                        text = text.Remove(i, 1).Insert(i, "”");
                    }
                    else
                    {
                        if (openingQuote)
                        {
                            // replace with opening quote
                            text = text.Remove(i, 1).Insert(i, "“");
                            openingQuote = false;
                        }
                        else
                        {
                            // replace with closing quote
                            text = text.Remove(i, 1).Insert(i, "”");
                            openingQuote = true;
                        }
                    }
                }

                // check for a single quote
                if (text[i] == '\'')
                {
                    // if openingSingleQuote
                    if (openingSingleQuote)
                    {
                        // replace with opening single quote
                        text = text.Remove(i, 1).Insert(i, "‘");
                        openingSingleQuote = false;
                    }
                    else
                    {
                        // replace with closing single quote
                        text = text.Remove(i, 1).Insert(i, "’");
                        // if the next character is a space or punctuation or end of line then  we are then opening quotes.
                        if (i < text.Length && char.IsLetterOrDigit(text[i + 1]))
                            openingSingleQuote = true;
                    }
                }



            } // end for loop

            File.WriteAllText(newStoryPath, text);

        }


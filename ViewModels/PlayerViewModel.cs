        public Bitmap? RenderBitMap(int width = 1800, int topHeight = 450, int bottomHeight = 450)
        {
            var myRendererSettings = new StandardWaveFormRendererSettings();
            myRendererSettings.Width = width;
            myRendererSettings.TopHeight = topHeight;
            myRendererSettings.BottomHeight = bottomHeight;

            var myPeakProvider = new AveragePeakProvider(4); // e.g. 4
            var renderer = new WaveFormRenderer();
            var audioFileReader = new AudioFileReader(
                Support.Support.FixImagePath(CurrentTrack.TrackPath)
                );
            System.Drawing.Image image = renderer.Render(audioFileReader, myPeakProvider, myRendererSettings);

            Bitmap? imageAv = Support.Support.GetBMPFromBitmap(image);
            return imageAv;
        }

        private void NextAlbumTrack()
        {
            if (CurrentAlbum == null && CurrentTrack.Album == null) return;
            CurrentAlbum = CurrentTrack.Album;
            int index = CurrentAlbum.AlbumTracks.IndexOf(CurrentTrack);
            if (index < CurrentAlbum.AlbumTracks.Count - 1)
            {
                CurrentTrack = CurrentAlbum.AlbumTracks[index + 1];
                ImageHeight = 500;
                ImageWidth = 1800;
                ImageBMP = RenderBitMap(ImageWidth, ImageHeight / 2, ImageHeight / 2);
                if (!string.IsNullOrEmpty(CurrentTrack.TrackPath))
                {
                    if (CurrentTrack.TrackPath.Contains("file://"))
                    {
                        // is a uri
                        Uri mrl = new Uri(CurrentTrack.TrackPath);
                        CurrentTrack.TrackPath = mrl.LocalPath;
                    }
                    MoviePath = Support.Support.FixImagePath(CurrentTrack.TrackPath);
                    if (File.Exists(MoviePath))
                    {
                        if (AutoPlay)
                        {
                            if (MediaPlayer.Media != null) MediaPlayer.Media.Dispose();
                            playing = false;
                            Avalonia.Threading.Dispatcher.UIThread.Post(() =>
                            {
                                Media? media = null;
                                media = new Media(_libVlc, new Uri(MoviePath));
                                MediaPlayer.Media = media;

                                MediaPlayer.Play();
                                playing = true;
                                MediaPlayer.Position = 0;
                                if (TrackGrid != null)
                                {
                                    TrackGrid.ScrollIntoView(CurrentTrack, null);
                                }
                            });
                        }
                    }
                }
            }
            else CurrentTrack = null;
        }

        private async Task<Media> ParseMedia()
        {
            Media media = new Media(_libVlc, new Uri(MoviePath));
            await media.Parse(MediaParseOptions.ParseNetwork);
            var mp = media.SubItems.First();
            return mp;
        }

        private void PrevAlbumTrack()
        {
            int index = CurrentAlbum.AlbumTracks.IndexOf(CurrentTrack);
            if (index > 0)
            {
                CurrentTrack = CurrentAlbum.AlbumTracks[index - 1];
                MoviePath = Support.Support.FixImagePath(CurrentTrack.TrackPath);
                if (AutoPlay)
                {
                    playing = false;
                    Play();
                }
            }
            else CurrentTrack = null;
        }

        private async void SetAlbumPath(Album currentAlbum, List<string> xspfFiles)
        {
            AutoPlay = false;
            if (xspfFiles != null && xspfFiles.Count > 0)
            {
                MoviePath = xspfFiles.First();
                Media? mp = await ParseMedia();
                if (mp != null && mp.SubItems.Count > 0)
                {
                    Media? track = mp.SubItems[0];
                    Uri mrl = new Uri(track.Mrl);
                    MoviePath = Support.Support.FixImagePath(mrl.LocalPath);
                    CurrentTrack = CurrentAlbum.AlbumTracks.First();
                }
                AutoPlay = true;
            }
            else if (currentAlbum != null)
            {
                CurrentTrack = CurrentAlbum.AlbumTracks.First();
                MoviePath = Support.Support.FixImagePath(CurrentTrack.TrackPath);
            }
            ImageHeight = 500;
            ImageWidth = 1800;
            ImageBMP = RenderBitMap(ImageWidth, ImageHeight / 2, ImageHeight / 2);
            AutoPlay = true;
        }
        private void SetPercent()
        {
            if (!playing) return;
            long movieLengtthMsecs = MediaPlayer.Time;

            double percent = MediaPlayer.Position * 100;
            progress = percent;
            ProgressInt = (int)percent;
            this.RaisePropertyChanged(nameof(Progress));
            this.RaisePropertyChanged(nameof(ProgressX));

            // get movie current time msecs

            TimeSpan elapsedTime = TimeSpan.FromMilliseconds(movieLengtthMsecs);

            Percent = elapsedTime.ToString(@"hh\:mm\:ss") + " - " + (percent).ToString("0.00") + "%";
        }

        private void SetPosition(float position)
        {
            // position is the percentage along film track

            MediaPlayer.Position = position / 100;
        }

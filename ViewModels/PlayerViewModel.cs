        private string DoAutoComplete(string bookmarkName)
        {
            string? oldText = bookmarkName;
            if (CurrentMovie != null)
            {
                //MainWindowViewModel? vm = GetMainWindowViewModel();

                List<Bookmark> found = CurrentMovie.Bookmarks
                    .ToList()
                    .FindAll(
                        b =>
                            b.Name.ToLower().Contains(oldText.ToLower())
                            && b.Name.ToLower().IndexOf(bookmarkName.ToLower()) == 0
                    );

                if (found != null && found.Count > 0)
                {
                    oldText += (found.Count).ToString();
                }
            }
            return oldText;
        }


        public void CreateNewStory()
        {
            // if NewStoryPath is null or empty set to default
            string testPath = string.IsNullOrEmpty(NewStoryPath) ? @"K:\Drive_I\Stories\NewDocument.docx" : NewStoryPath;


            // create standard properties settings a set of WordProperties
            WordProperties props = new()
            {
                Title = NewStoryTitle,
                Author = NewStoryTitle
            };
            // create a body to pass to CreateNewDocument
            Body body = new();
            Paragraph? title = null;
            // if NewStoryTitle is not null or empty add to body
            // add a title in a title style paragraph
            if (!string.IsNullOrEmpty(NewStoryTitle))
            {
                title = WordXML.CreateTitle(NewStoryTitle);
            }
            else
            {
                title = WordXML.CreateTitle("This is an example title");
            }
            body.Append(title);

            // if NewStoryAuthor is not null or empty add to body
            if (!string.IsNullOrEmpty(NewStoryAuthor))
            {
                Paragraph author = WordXML.CreateAuthorParagraph("By " + NewStoryAuthor);
                body.Append(author);
            }
            else
            {
                Paragraph author = WordXML.CreateAuthorParagraph("Example Author");
                body.Append(author);
            }

            // if NewStoryTextFile is not null or empty read text file and add to body
            if (!string.IsNullOrEmpty(NewStoryTextFile) && File.Exists(NewStoryTextFile))
            {
                WordXML.AppendTextFileToBody(body, NewStoryTextFile);
            }
            else
            {
                // create an example paragraph
                Paragraph test = new();
                Run run_paragraph = new();
                Text text_paragraph = new Text("This is a test");
                run_paragraph.Append(text_paragraph);
                test.Append(run_paragraph);
                body.Append(test);
            }

            // create CustomProperties settings a set of WordProperties
            WordProperties customProps = new WordProperties()
            {

            };

            // create the actual document
            WordXML.CreateNewDocument(NewStoryPath, body, props, customProps);


            // add styles to the document this seems to work best if done after creating the document
            WordXML.ReplaceStyles(WordXML.stylesPath, NewStoryPath);
        }


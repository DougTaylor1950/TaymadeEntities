                {
                    // insert by a stored procedure to get the id of the new entity
                    UnboundGridData? temp = DataController.SandboxEntities.CreateUnbound(FileName, FileLength.Value, DurationSeconds.Value, CreationTime, Name);
                    if (temp != null)
                    {
                        this.Id = temp.Id;
                    }
                    else
                        temp = DataController.SandboxEntities.UnboundGridData.Where(u => u.FileName.ToLower() == FileName.ToLower()).FirstOrDefault();
                    success = true;
                }
                catch (Exception ex)
                {
                    success = false;
                    //throw;
                }
                return success;
            }
            else
                return this.Save();

        }


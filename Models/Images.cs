        public void BuildSubFolders()
        {
            MovieImage? images = DataController.MovieImageEntity.MovieImage.Where(i => i.FolderType == "Root").FirstOrDefault();
            // get subfolders
            if (images != null)
            {
                LastId = images.LastId;
                Id = images.Id;
                FolderType = images.FolderType;

                // get an ordered list of sub folders
                SubDirectoryList = new ObservableCollection<MovieImage>(DataController.MovieImageEntity.MovieImage.Where(i => i.ParentId == Id).OrderBy(d => d.Name.ToLower()).ToList());

                if (LastId != null)
                {
                    // get an ordered list of images
                    images = SubDirectoryList.Where(f => f.Id == LastId).OrderBy(i => i.Name).FirstOrDefault();
                    if (images != null)
                    {
                        CurrentImageFolder = images;
                        // see if we can find sub folder
                        if (CurrentImageFolder.LastId != null)
                        {
                            images = CurrentImageFolder.SubDirectoryList.Where(f => f.Id == CurrentImageFolder.LastId).FirstOrDefault();
                            CurrentSubFolder = images;

                            if (images != null && images.ImageItems.Count > 0 && !string.IsNullOrEmpty(images.LastImageName))
                            {
                                CurrentImageItem = images.ImageItems.Where(it => it.ImageName == images.LastImageName).FirstOrDefault();
                                MainSupport.ScrollItemImagesIntoView(CurrentImageItem);
                            }
                        }
                    }
                }
                else CurrentImageFolder = SubDirectoryList.FirstOrDefault();


            }
        }

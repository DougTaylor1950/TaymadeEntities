        /// <summary>
        /// Gets the children.
        /// </summary>
        /// <param name="heading1">The heading1.</param>
        /// <autogeneratedoc />
        private void GetChildren(WordHeadings heading1)
        {
            if (heading1 != null && heading1.HeadingLevel < 3 && heading1.ParentId >0)
            {
                int currentHeadingLevel = heading1.HeadingLevel.Value;
                // Ensure Children is initialized, if not clear it
                if (heading1.Children == null)
                {
                    heading1.Children = new ObservableCollection<WordHeadings>();
                } else heading1.Children.Clear();

                // Find all children of this heading1, sorted by StringId
                var children = this.Where(x => x.ParentId == heading1.Id  && x.HeadingLevel == currentHeadingLevel+1).OrderBy(x => x.StringId).Distinct(new WordHeadingsComparer()).ToList();
                // If there are children, add them to the hierarchical list
                if (children.Any())
                {
                    foreach (var child in children)
                    {
                        heading1.Children.Add(child);
                        // Recursively get children of this child
                        if (child.HeadingLevel < 3)
                        {
                            this.GetChildren(child);
                        }
                    }
                }
            }
        }


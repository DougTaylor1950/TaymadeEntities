        public async void CreateStory()
        {
            var window = Support.GetMainWindow();
            if (window != null)
            {
                Uri uri = new Uri(DefaultStoryDirectory);
                Avalonia.Platform.Storage.IStorageFolder? defaultStoryFolder = await window.StorageProvider.TryGetFolderFromPathAsync(uri);
                // Use StorageProvider API to pick a folder
                var folder = await window.StorageProvider.OpenFolderPickerAsync(new Avalonia.Platform.Storage.FolderPickerOpenOptions
                {
                    Title = "Story folder location",
                    SuggestedStartLocation = defaultStoryFolder
                });

                // create a fileinfo object to be used later
                System.IO.FileInfo? fileInfo = null;

                if (folder != null && folder.Count > 0)
                {
                    var result = folder[0].Path.LocalPath;
                    DateTime minDate = new DateTime(1970, 1, 1);

                    if (!string.IsNullOrEmpty(result))
                    {
                        Uri resultUri = new Uri(result);
                        Avalonia.Platform.Storage.IStorageFolder? resultFolder = await window.StorageProvider.TryGetFolderFromPathAsync(resultUri);
                        // Use StorageProvider API to pick a file
                        var files = await window.StorageProvider.OpenFilePickerAsync(new Avalonia.Platform.Storage.FilePickerOpenOptions
                        {
                            SuggestedStartLocation = resultFolder
                        });

                        if (files != null && files.Count > 0 && !string.IsNullOrEmpty(files[0].Path.LocalPath))
                        {
                            string newStoryPath = files[0].Path.LocalPath;

                            // get FileInfo
                            fileInfo = new System.IO.FileInfo(newStoryPath);

                            DateTime lastWriteTime = minDate;

                            if (fileInfo.LastWriteTime > minDate) lastWriteTime = fileInfo.LastWriteTime;
                            else if (fileInfo.CreationTime > minDate) lastWriteTime = fileInfo.CreationTime;
                            else lastWriteTime = DateTime.Now;
                            // check extension
                            string ext = Path.GetExtension(newStoryPath).ToLower();

                            if (ext.Contains("xt"))
                            {

                                // make a backup copy of the text file
                                string backupPath = Path.GetDirectoryName(newStoryPath) + @"\" + Path.GetFileNameWithoutExtension(newStoryPath) + "_backup" + Path.GetExtension(newStoryPath);
                                File.Copy(newStoryPath, backupPath, true);

                                // reformat the document converting it into paragraphs and removing unwanted characters
                                ReformatDocument(newStoryPath);

                                string renamed = Path.GetDirectoryName(newStoryPath) + @"\" + Path.GetFileNameWithoutExtension(newStoryPath) + ".docx";

                                int index = 1;
                                // need to check if that name exists
                                while (File.Exists(renamed))
                                {
                                    // if it does add an incrementor
                                    renamed = Path.GetDirectoryName(newStoryPath) + @"\" + Path.GetFileNameWithoutExtension(newStoryPath) + index.ToString().Trim() + ".docx";
                                    index += 1;
                                }

                                // convert text file to docx
                                if (CreateDocXFile(newStoryPath))
                                {
                                    // save original file name
                                    string originalFileName = newStoryPath;
                                    // rename to doc and set property to indicate it is a text file originally
                                    newStoryPath = renamed;

                                    // we canb now delete the text file
                                    if (File.Exists(originalFileName))
                                    {
                                        File.Delete(originalFileName);
                                    }

                                }

                                if (fileInfo.LastWriteTime >= minDate)
                                {
                                    File.SetCreationTime(newStoryPath, lastWriteTime);
                                }
                                // we should have a .docx file at this stage
                            }
                            else if (ext == ".doc")
                            {
                                try
                                {
                                    // fileInfo = new System.IO.FileInfo(newStoryPath);

                                    // use DocToDocX App with the story file name as argument call with CliWrap
                                    string appPath = @"F:\Users\Doug\Source\Repos\DocToDocX\DocToDocX\bin\Debug\net9.0\DocToDocx.exe";
                                    string workingDir = @"K:\Drive_I\Stories";
                                    CommandResult? res;

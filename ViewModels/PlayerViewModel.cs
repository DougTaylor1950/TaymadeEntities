        public void AddMark(string bookmarkName)
        {
            if (CurrentMovie != null && CurrentMovie.Bookmarks != null)
            {
                Bookmark oldBookmark = CurrentMovie.GetLastBookmark();

                bookmarkName = DoAutoComplete(bookmarkName);

                double time = 1;

                if (MediaPlayer != null)
                {
                    if (MediaPlayer.IsPlaying)
                    {
                        time = MediaPlayer.Length * MediaPlayer.Position / 1000;
                    }
                    else if (!MediaPlayer.IsPlaying && paused)
                    {
                        time = MediaPlayer.Length * MediaPlayer.Position / 1000;
                    }
                    else if (oldBookmark != null && oldBookmark.Time != null)
                    {
                        time = oldBookmark.Time.Value + 10;
                    }

                    //BookmarkName = bookmarkName;
                    //MovieName = CurrentMovie.MovieName;

                    int mId = CurrentMovie.Id;
                    Bookmark bookmark = new Bookmark()
                    {
                        Name = bookmarkName,
                        Time = time,
                        MovieID = mId,
                        Type = "BOOKMARK"
                    };

                    AddActualBookmark(bookmark);

                    Bookmark = bookmark;
                    CurrentBookmark = bookmark;
                }
            }
        }


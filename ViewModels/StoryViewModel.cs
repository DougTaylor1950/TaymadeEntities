                                        .WithWorkingDirectory(workingDir);

                                    await cmd.ExecuteAsync();

                                    // check to see if we have a docx file
                                    if (File.Exists(newStoryPath + "x"))
                                    {
                                        string originalFile = newStoryPath;
                                        newStoryPath = newStoryPath + "x";
                                        // we should delete the old doc file.
                                        File.Delete(originalFile);
                                    }

                                    // copy styles using WorXML.ReplaceStyles
                                    //  WordXML.ReplaceStyles(WordXML.stylesPath, newStoryPath);


                                }
                                catch (Exception ex)
                                {


                                }
                            }
                            CurrentStory = Story.Create(newStoryPath);

                            // add fileinfo

                            if (CurrentStory == null) CurrentStory = DataController.StoryController.GetStories().MaxBy(s => s.Id);

                            if (CurrentStory == null) return;

                                if (fileInfo != null)
                            {
                                CurrentStory.Added = DateTime.Now;
                                CurrentStory.Creation = lastWriteTime;

                                CurrentStory.Save();
                            }

                            // create a storytransinfo instance set currentstryId and update it
                            //StoryTransInfo? storyTransInfo = new StoryTransInfo();
                            StoryTransInfo.GetInstance().CurrentStoryId = CurrentStory.Id;
                            StoryTransInfo.Update();

                            // Get document properties to set creation time

                            GetPropsOverride(lastWriteTime);

                            //StoryDictionary? storyDictionary = new StoryDictionary(currentStory.Id);
                            //if (storyDictionary.Id < 1)
                            //{
                            //    storyDictionary.Insert();
                            //}

                            // create the dictionary file
                            // if the file exists delete it
                            // and create a new one

                            // clear the file K:\Drive_I\Stories\CurrentStory.dic

                            if (File.Exists(CurrentStory.StoryDictionary?.DictionaryPath))
                            {
                                File.Delete(CurrentStory.StoryDictionary?.DictionaryPath);
                            }

                            CurrentStory.StoryDictionary.CreateCustomDictionary();

                            // check wordheadingslist and section breaks exist if not create the list and add a section break
                            if (CurrentStory.WordHeadingList == null || CurrentStory.WordHeadingList.Count == 0)
                            {
                                CurrentStory.WordHeadingList = new List<WordHeadings>();
                            }

                            if (CurrentStory.SectionBreaks == null || CurrentStory.SectionBreaks.Count == 0)
                            {
                                CurrentStory.SectionBreaks = new ObservableCollection<WordHeadings>();
                            }

                            // There must be at least one section break in the document create heading
                            WordHeadings heading = new WordHeadings()
                            {
                                HeadingLevel = 0,
                                StringId = "Sect_01",
                                HeadingText = "Sect_01",
                                StoryId = CurrentStory.Id
                            };
                            CurrentStory.SectionBreaks.Add(heading);
                            CurrentStory.WordHeadingList.Add(heading);
                            heading.StoryId = CurrentStory.Id;
                            heading.Insert();

                            
                            
                            if (CurrentStory != null)
                            {

                                if (StoryList != null)
                                {
                                    StoryList.Add(CurrentStory);
                                }
                                // set this story in StoryProperties as current story
                                Models.DataController.StoryProperties.LastStoryId = CurrentStory.Id;
                                Models.DataController.StoryProperties.Save();
                                LastStoryId = CurrentStory.Id;
                                CurrentStory.Save();
                            }
                            DoClear();
                        }
                    }
                }
            }
        }



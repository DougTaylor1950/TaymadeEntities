        public void SetImagesFrameSetIndex()
        {
            if (CurrentSubFolder.FrameSetHeader != null && CurrentSubFolder.FrameSetHeader.FrameSetList != null)
            {
                // sort FrameSetlist by Index

                CurrentSubFolder.FrameSetHeader.FrameSetList = CurrentSubFolder.FrameSetHeader.FrameSetList.OrderBy(f => f.Index).ToList();
                //int indexer = 1;
                foreach (FrameSet frameSet in CurrentSubFolder.FrameSetHeader.FrameSetList)
                {
                    //frameSet.Index = indexer;
                    //indexer += 1;
                    for (int i = frameSet.StartImage - 1; i < CurrentSubFolder.ImageItems.Count; i++)
                    {
                        var item = CurrentSubFolder.ImageItems[i];
                        item.FrameSetIndex = frameSet.Index;
                    }
                }

            }
        }


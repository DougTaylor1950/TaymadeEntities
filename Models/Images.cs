    public class ImageItem : ModelBase
    {
        private Avalonia.Media.Imaging.Bitmap? imageBMP;
        private bool? bMPVisible;
        private bool? selected;
        private string? imageName;

        public string? ImagePath { get; set; }

        public string? ImageName
        {
            get
            {
                if (string.IsNullOrEmpty(imageName))
                {
                    if (!string.IsNullOrEmpty(ImagePath))
                    { imageName = Path.GetFileNameWithoutExtension(ImagePath); }

                    else imageName = "--";
                }
                return imageName;
            }
            set
            {
                string oldvalue = imageName;
                this.RaiseAndSetIfChanged(ref imageName, value);

                // see if has changed
                if (oldvalue != imageName)
                {
                    string newPath = ImagePath.Replace(oldvalue, imageName);
                    File.Move(ImagePath, newPath);
                    ImagePath = newPath;

                }
            }
        }

        [NotMapped]
        public Avalonia.Media.Imaging.Bitmap? ImageBMP
        {
            get
            {
                if (imageBMP == null)
                {
                    Support.Support.SetImageBMP(ImagePath, out imageBMP);
                }

                BMPVisible = (imageBMP != null);

                return imageBMP;
            }
            set
            {
                imageBMP = value;
                BMPVisible = (imageBMP != null);
            }
        }

        [NotMapped]
        public bool? BMPVisible { get => bMPVisible; set => bMPVisible = value; }

        [NotMapped]
        public bool? Selected { get => selected; set => this.RaiseAndSetIfChanged(ref selected, value); }
    }


                                            stringhead1 = infoset[3].Trim();

                                            WordHeadings? head1 = CurrentStory.WordHeadingList?.Find(h => h.StringId.ToLower() == stringhead1.ToLower() && h.HeadingLevel == 1);
                                            // set parentId if not null and headings is not null
                                            if (head1 != null && headings != null)
                                            {
                                                // update parent id
                                                if (headings.ParentId != head1.Id)
                                                {
                                                    headings.ParentId = head1.Id;
                                                    headings.Update();
                                                }
                                            }

                                            // see if heading is in head1 children list if not add it
                                            if (head1 != null && headings != null)
                                            {
                                                WordHeadings? childHeading = head1.Children.Where(h => h.Id == headings.Id).FirstOrDefault();
                                                if (childHeading == null)
                                                {
                                                    head1.Children.Add(headings);
                                                }
                                            }
                                        }
                                        GetHeadings2();
                                    }
                                    success = await CurrentStory.SaveAsync();
                                    //viewModel.CreateNewHierachy(CurrentStory);
                                    CurrentStory.Info = CurrentStory.StoryInfo.ToInfo();
                                    break;


                                case ExitedCommandEvent exited:

                                    if (exited.ExitCode == 0)
                                    {
                                        if (extn == ".doc")
                                        {
                                            // check to see if we have converted to docx?

                                            if (File.Exists(fixedPath + "x"))
                                            {
                                                // it does exist
                                                string oldPath = fixedPath;
                                                CurrentStory.Path += "x";
                                                File.Delete(oldPath);

                                                CurrentStory.DocumentExtn = ".docx";
                                                CurrentStory.PathWrong = false;
                                                // save the story now
                                                success = await CurrentStory.SaveAsync();
                                            }
                                        }
                                        

                                        // check to see if there is a storydictionary file
                                        if (CurrentStory.StoryDictionary != null)
                                        {
                                            try
                                            {
                                                CurrentStory.StoryDictionary.LoadDictionary();
                                                

                                            }
                                            catch (Exception)
                                            {

                                                // throw;
                                            }
                                            CurrentStory.StoryDictionary = null;
                                        }
                                        CreateNewHierachy(currentStory);
                                    }
                                    break;

                                // deaL with errors
                                case StandardErrorCommandEvent stdErr:
                                    // _output.WriteLine($"Err> {stdErr.Text}");
                                    // process received data
                                    string errorOutput = stdErr.Text;
                                    if (errorOutput.Contains("Error:"))
                                    {
                                        // handle error BY WRITING TO NLOG
                                        //NLog.Logger logger = NLog.LogManager.GetCurrentClassLogger();
                                        //logger.Error($"Error in Word processing: {errorOutput}");
                                        Support.Logger.Error($"Error in Word processing: {errorOutput}");

                                    }
                                    break;
                            }
                        }

                        if (mainWindow != null) mainWindow.WindowState = WindowState.Maximized;
                    }
                }
            }
            catch (Exception ex)
            {
                // log the error
                Support.Logger.Error(ex, "Error in EditStory");

                //// use Avalonia MessageBox to show error    

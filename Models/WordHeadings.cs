        public ObservableCollection<WordHeadings> HierarchicalList
        {
            get
            {
                ObservableCollection<WordHeadings> hierarchicalList = new ObservableCollection<WordHeadings>();

                // Get list of heading_level 0 then go through list and find children
                var heading1s = this.Where(x => x.HeadingLevel == 0).Distinct( new WordHeadingsComparer()).OrderBy(x => x.StringId).ToList();
                foreach (var heading1 in heading1s)
                {
                    // Add the heading1 to the hierarchical list
                    hierarchicalList.Add(heading1);
                    this.GetChildren(heading1);
                }
                return hierarchicalList;
            }

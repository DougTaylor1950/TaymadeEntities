        public static Bitmap? GetBMP(string fileName)
        {
            Bitmap? retBMP = null;

            if (System.IO.File.Exists(fileName))// && GetOS() == "WinNT")
            {
                System.Drawing.Bitmap sBitmap = new System.Drawing.Bitmap(System.Drawing.Image.FromFile(fileName));

                using (System.IO.MemoryStream memory = new System.IO.MemoryStream())
                {
                    sBitmap.Save(memory, System.Drawing.Imaging.ImageFormat.Bmp);
                    memory.Position = 0;

                    retBMP = new Bitmap(memory);
                }
            }
            return retBMP;
        }

        public static string Trimnumbersoff(string name)
        {
            int i = name.Length - 1;

            int j = name.Length - 1;

            while (i > 0 && char.IsDigit(name[i]))
            {
                i -= 1;
            }

            name = name.Substring(0, i + 1);
            return name;
        }


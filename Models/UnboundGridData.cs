        public static UnboundGridData Create(string folderPath, string fileName, string sep = "\\")
        {
            UnboundGridData unboundGridData = new UnboundGridData();
            unboundGridData.Folder = folderPath;
            string dataFileName = folderPath + sep + fileName;
            unboundGridData.FileName = dataFileName;
            unboundGridData.Name = fileName.Trim();
            unboundGridData.FilePath = dataFileName;

            System.IO.FileInfo fileInfo = new System.IO.FileInfo(dataFileName);
            unboundGridData.FileLength = fileInfo.Length;
            unboundGridData.CreationTime = fileInfo.CreationTime.ToString("yyyy/MM/dd HH:mm");
            unboundGridData.FileInfo = fileInfo;
            unboundGridData.Insert();
            if (unboundGridData.Id > 0) unboundGridData.Save();

            return unboundGridData;
        }

        private void FindCodesForItem(StoryCast item)
        {
            if (item.CastId != null && item.CastId > 0)
            {
                item.StoryId = CurrentStory.Id;
                string searchCode = "id:" + item.CastId.ToString().Trim() + ";";
                if (CurrentStory.Codes.Contains(searchCode, StringComparison.OrdinalIgnoreCase))
                {
                    int index1 = CurrentStory.Codes.IndexOf(searchCode, StringComparison.OrdinalIgnoreCase);
                    int index2 = CurrentStory.Codes.IndexOf("Id:", index1 + 1, StringComparison.OrdinalIgnoreCase);
                    // check we have found something 
                    if (index1 >= 0 && index2 > 0)
                    {
                        string code = CurrentStory.Codes.Substring(index1 + searchCode.Length, index2 - index1 - 5);
                        item.Codes = code;
                    }
                }
                // update or insert
                if (item.Pk > 0)
                {
                    item.Update();
                    //DataController.SandboxEntities.Entry(item).State = EntityState.Modified;
                }
                else
                {
                    item.Insert();
                    if (item.Pk > 0) item.Update();
                }
            }
        }


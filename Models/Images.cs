        public void ImageFolderSelectionChanged(object? e)
        {
            //if (CurrentImageFolder != null && CurrentImageFolder.ImageItems != null)
            //CurrentImageFolder.ImageItems.DiscardBitmaps();

            CurrentImageFolder = e as MovieImage;

            if (CurrentImageFolder != null && CurrentImageFolder.ImageItems.Count > 0)
            {
                if (!string.IsNullOrEmpty(CurrentImageFolder.LastImageName))
                {
                    CurrentImageItem = CurrentImageFolder.ImageItems.Find(i => i.ImageName == CurrentImageFolder.LastImageName);
                }
                else
                    CurrentImageItem = CurrentImageFolder.ImageItems.FirstOrDefault();
                CurrentImageFolder.Info = "Images/Folders : " + CurrentImageFolder.ImageItems.Count.ToString();

            }

            if (CurrentImageFolder.SubDirectoryList != null)
            {
                CurrentSubDirectoryList = new ObservableCollection<MovieImage>(CurrentImageFolder.SubDirectoryList.OrderBy(x => x.Name));
                CurrentSubFolder = CurrentImageFolder.SubDirectoryList.Where(f => f.Id == CurrentImageFolder.LastId).FirstOrDefault();
            }
            else

                CurrentSubFolder = null;
        }

        public void SubSelectionChanged(MainWindowViewModel? mvvm, object? e)
        {
            if (mvvm != null && e != null)
            {

                CurrentSubFolder = e as MovieImage;
                //.CurrentSubFolder.Properties.Load();

                if (CurrentSubFolder != null)
                {

                    CurrentImageFolder.LastId = CurrentSubFolder.Id;
                    CurrentImageFolder.Save();

                    if (CurrentSubFolder.ImageItems.Count > 0)
                    {

                        if (!string.IsNullOrEmpty(CurrentSubFolder.LastImageName))
                        {
                            CurrentImageItem = CurrentSubFolder.ImageItems.Find(i => i.ImageName == CurrentSubFolder.LastImageName);
                        }
                        else
                            CurrentImageItem = CurrentSubFolder.ImageItems.FirstOrDefault();
                        if (CurrentImageItem != null) CurrentImageItem.Selected = true;
                        CurrentImageFolder.Info = "Images : " + CurrentSubFolder.ImageItems.Count.ToString();

                        HasMP4 = false;
                        HasMovieEntity = false;
                        Movies? movie = HasMovie();

                        mvvm.HasMovie = movie != null;
                        MVVM = mvvm;
                        CurrentMovie = movie;

                        if (movie != null)
                        {
                            CurrentSubFolder.Movies = movie;
                            CurrentSubFolder.MovieId = movie.Id;
                            HasMovieEntity = true;
                            MovieInfo = movie.ToString();
                        }
                        else
                        {
                            CurrentSubFolder.Movies = null;
                            MovieInfo = "No Movie Found";
                        }



                        string outputDirectory = CurrentSubFolder.Path + @"\temp\";
                        string outputfile = outputDirectory + System.IO.Path.GetFileNameWithoutExtension(CurrentSubFolder.Path) + ".mp4";


                    }
                }
                //if (.CurrentImageFolder.SubDirectoryList != null) .CurrentSubDirectoryList = .CurrentImageFolder.SubDirectoryList;

            }
        }

